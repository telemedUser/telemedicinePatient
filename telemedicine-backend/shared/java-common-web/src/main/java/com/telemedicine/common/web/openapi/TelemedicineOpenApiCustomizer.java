package com.telemedicine.common.web.openapi;

import com.telemedicine.common.core.constants.Headers;
import io.swagger.v3.oas.models.Components;
import io.swagger.v3.oas.models.OpenAPI;
import io.swagger.v3.oas.models.Operation;
import io.swagger.v3.oas.models.media.ArraySchema;
import io.swagger.v3.oas.models.media.Content;
import io.swagger.v3.oas.models.media.IntegerSchema;
import io.swagger.v3.oas.models.media.MediaType;
import io.swagger.v3.oas.models.media.ObjectSchema;
import io.swagger.v3.oas.models.media.Schema;
import io.swagger.v3.oas.models.media.StringSchema;
import io.swagger.v3.oas.models.parameters.HeaderParameter;
import io.swagger.v3.oas.models.responses.ApiResponse;
import io.swagger.v3.oas.models.responses.ApiResponses;
import io.swagger.v3.oas.models.security.SecurityRequirement;
import io.swagger.v3.oas.models.security.SecurityScheme;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import org.springdoc.core.customizers.OpenApiCustomizer;

/**
 * Injects the platform's shared API conventions into every generated OpenAPI document.
 *
 * <p>Without this, each of the seventeen services would have to declare the same error responses,
 * the same correlation header and the same Keycloak security scheme by hand on every operation.
 * That is boilerplate nobody maintains, so the published contracts drift from what the services
 * actually return — which is precisely what the interoperability requirement forbids.
 */
public class TelemedicineOpenApiCustomizer implements OpenApiCustomizer {

    private static final String PROBLEM_SCHEMA = "ProblemDetail";
    private static final String VIOLATION_SCHEMA = "Violation";
    private static final String SECURITY_SCHEME = "keycloak";
    private static final String PROBLEM_MEDIA_TYPE = "application/problem+json";

    /**
     * Statuses every operation can produce because the shared filters and advice can raise them.
     */
    private static final Map<String, String> UNIVERSAL_RESPONSES =
            Map.of(
                    "400", "Malformed or invalid request",
                    "401", "Missing or invalid credentials",
                    "403", "Authenticated but not permitted, or consent missing",
                    "404", "Resource not found",
                    "409", "Conflicts with the current state of the resource",
                    "422", "Semantically invalid request",
                    "429", "Rate limit exceeded",
                    "500", "Unexpected internal error");

    private final String jwkSetUri;

    public TelemedicineOpenApiCustomizer(String jwkSetUri) {
        this.jwkSetUri = jwkSetUri;
    }

    @Override
    public void customise(OpenAPI openApi) {
        Components components = openApi.getComponents();
        if (components == null) {
            components = new Components();
            openApi.setComponents(components);
        }
        registerSchemas(components);
        registerSecurityScheme(openApi, components);

        if (openApi.getPaths() == null) {
            return;
        }
        openApi.getPaths()
                .values()
                .forEach(pathItem -> pathItem.readOperations().forEach(this::decorate));
    }

    private void decorate(Operation operation) {
        ApiResponses responses = operation.getResponses();
        if (responses == null) {
            responses = new ApiResponses();
            operation.setResponses(responses);
        }
        for (Map.Entry<String, String> entry : UNIVERSAL_RESPONSES.entrySet()) {
            // An operation that documents a status itself keeps its own, richer description.
            responses.computeIfAbsent(entry.getKey(), ignored -> problemResponse(entry.getValue()));
        }
        addCorrelationHeaderParameter(operation);
    }

    private void addCorrelationHeaderParameter(Operation operation) {
        boolean alreadyDeclared =
                operation.getParameters() != null
                        && operation.getParameters().stream()
                                .anyMatch(
                                        p -> Headers.CORRELATION_ID.equalsIgnoreCase(p.getName()));
        if (alreadyDeclared) {
            return;
        }
        operation.addParametersItem(
                new HeaderParameter()
                        .name(Headers.CORRELATION_ID)
                        .description(
                                "Journey correlation id. Generated by the gateway when absent and"
                                        + " echoed on every response.")
                        .required(false)
                        .schema(new StringSchema()));
    }

    private ApiResponse problemResponse(String description) {
        return new ApiResponse()
                .description(description)
                .content(
                        new Content()
                                .addMediaType(
                                        PROBLEM_MEDIA_TYPE,
                                        new MediaType()
                                                .schema(
                                                        new Schema<>()
                                                                .$ref(
                                                                        "#/components/schemas/"
                                                                                + PROBLEM_SCHEMA))));
    }

    private void registerSchemas(Components components) {
        if (components.getSchemas() != null
                && components.getSchemas().containsKey(PROBLEM_SCHEMA)) {
            return;
        }
        components.addSchemas(VIOLATION_SCHEMA, violationSchema());
        components.addSchemas(PROBLEM_SCHEMA, problemSchema());
    }

    // The swagger-models API predates generics on its property maps; the raw type is theirs.
    @SuppressWarnings({"rawtypes", "unchecked"})
    private Schema<?> violationSchema() {
        Map<String, Schema> properties = new LinkedHashMap<>();
        properties.put("field", new StringSchema().description("Dotted path to the property"));
        properties.put("message", new StringSchema().description("Human-readable explanation"));
        properties.put(
                "rejectedValue",
                new StringSchema().description("Offending value, PHI-redacted; may be absent"));
        return new ObjectSchema()
                .description("A single field-level validation failure")
                .properties(properties);
    }

    @SuppressWarnings({"rawtypes", "unchecked"})
    private Schema<?> problemSchema() {
        Map<String, Schema> properties = new LinkedHashMap<>();
        properties.put(
                "type",
                new StringSchema()
                        .format("uri")
                        .description(
                                "Dereferenceable problem type under telemedicine.bupa/problems"));
        properties.put("title", new StringSchema().description("Short, human-readable summary"));
        properties.put("status", new IntegerSchema().description("HTTP status code"));
        properties.put("detail", new StringSchema().description("PHI-redacted explanation"));
        properties.put("instance", new StringSchema().description("Request path"));
        properties.put(
                "code",
                new StringSchema()
                        .description("Stable catalogue code such as TM-CNS-001")
                        .example("TM-CNS-001"));
        properties.put(
                "extensions",
                new ObjectSchema()
                        .description(
                                "RFC 9457 extension members: correlationId, traceId, timestamp,"
                                        + " category, retryable and violations")
                        .addProperty("correlationId", new StringSchema())
                        .addProperty("traceId", new StringSchema())
                        .addProperty("timestamp", new StringSchema().format("date-time"))
                        .addProperty("category", new StringSchema())
                        .addProperty(
                                "violations",
                                new ArraySchema()
                                        .items(
                                                new Schema<>()
                                                        .$ref(
                                                                "#/components/schemas/"
                                                                        + VIOLATION_SCHEMA))));
        return new ObjectSchema()
                .description("RFC 9457 problem document returned by every Telemedicine service")
                .properties(properties)
                .required(List.of("type", "title", "status"));
    }

    private void registerSecurityScheme(OpenAPI openApi, Components components) {
        if (components.getSecuritySchemes() != null
                && components.getSecuritySchemes().containsKey(SECURITY_SCHEME)) {
            return;
        }
        components.addSecuritySchemes(
                SECURITY_SCHEME,
                new SecurityScheme()
                        .type(SecurityScheme.Type.HTTP)
                        .scheme("bearer")
                        .bearerFormat("JWT")
                        .description("Keycloak-issued access token. JWKS: " + jwkSetUri));
        openApi.addSecurityItem(new SecurityRequirement().addList(SECURITY_SCHEME));
    }
}
