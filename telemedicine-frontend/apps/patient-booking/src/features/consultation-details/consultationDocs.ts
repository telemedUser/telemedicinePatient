import { buildPdf, downloadPdf, viewPdf, type PdfLine } from "@/shared/pdf/buildPdf";

/** The care-plan shape returned inside GET /consultations/{ref}/documents (plan field). */
export interface CarePlanData {
  appointmentId?: string;
  note?: { history?: string; findings?: string; assessment?: string; plan?: string };
  diagnoses?: { code: string; title: string; primary?: boolean }[];
  prescriptions?: {
    name: string; strength?: string | null; form?: string | null;
    frequency?: string | null; durationDays?: number | null; quantity?: number | null; instructions?: string | null;
  }[];
  followUp?: { enabled?: boolean; mode?: string | null; inDays?: number | null; date?: string | null };
  medicalLeave?: { enabled?: boolean; reason?: string | null; startDate?: string | null; endDate?: string | null };
  summary?: { text?: string | null; instructions?: string | null };
}

export interface DocsContext {
  plan: CarePlanData | null;
  prescriptionNumber?: string | null;
  medicalLeaveNumber?: string | null;
  issuedAt?: string | null;
  reference: string;            // appointment ref
  patientName: string;
  doctorName: string;
  doctorSpecialty?: string;
  mode: string;
  feeLabel?: string;            // e.g. "₹700" or "£25 · insurance policy cover applied"
}

export type DocKind = "prescription" | "medicalLeave" | "summary" | "receipt";

function fmtDate(iso?: string | null): string {
  if (!iso) return "";
  const d = new Date(iso);
  return Number.isNaN(d.getTime()) ? "" : d.toLocaleDateString("en-GB", { weekday: "short", day: "numeric", month: "short", year: "numeric" });
}
function fmtDateTime(iso?: string | null): string {
  if (!iso) return new Date().toLocaleString("en-GB", { day: "2-digit", month: "short", year: "numeric", hour: "2-digit", minute: "2-digit" });
  const d = new Date(iso);
  return Number.isNaN(d.getTime()) ? "" : d.toLocaleString("en-GB", { day: "2-digit", month: "short", year: "numeric", hour: "2-digit", minute: "2-digit" });
}

const BRAND = "Connected Care";

function header(title: string, ctx: DocsContext): PdfLine[] {
  return [
    { text: BRAND, style: "heading" },
    { text: title, style: "title" },
    { text: `Patient: ${ctx.patientName}`, style: "normal" },
    { text: `Physician: ${ctx.doctorName}${ctx.doctorSpecialty ? ` · ${ctx.doctorSpecialty}` : ""}`, style: "normal" },
    { text: `Reference: ${ctx.reference}   ·   Issued: ${fmtDateTime(ctx.issuedAt)}`, style: "muted" },
    { style: "rule" },
  ];
}

function footer(): PdfLine[] {
  return [
    { style: "spacer" },
    { style: "rule" },
    { text: "Electronic document generated by Connected Care. Valid without a wet signature.", style: "muted" },
  ];
}

/** Build the styled lines for a given document kind from the care plan. Returns null if the kind has no data. */
export function buildDocLines(kind: DocKind, ctx: DocsContext): PdfLine[] | null {
  const plan = ctx.plan;
  const primary = plan?.diagnoses?.find((d) => d.primary) ?? plan?.diagnoses?.[0];

  if (kind === "prescription") {
    const meds = plan?.prescriptions ?? [];
    if (meds.length === 0) return null;
    const lines: PdfLine[] = [
      ...header("Prescription", ctx),
      { text: ctx.prescriptionNumber ? `Prescription no. ${ctx.prescriptionNumber}` : "Prescription", style: "muted" },
      { style: "spacer" },
      { text: "Medicines", style: "heading" },
    ];
    meds.forEach((m) => {
      const name = `${m.name}${m.strength ? ` ${m.strength}` : ""}${m.form ? ` ${m.form}` : ""}`;
      const dir = [m.frequency, m.durationDays ? `${m.durationDays} days` : null, m.quantity ? `Qty ${m.quantity}` : null]
        .filter(Boolean).join(" · ");
      lines.push({ text: name, style: "normal" });
      if (dir) lines.push({ text: `   ${dir}`, style: "muted" });
      if (m.instructions) lines.push({ text: `   ${m.instructions}`, style: "muted" });
    });
    if (primary) {
      lines.push({ style: "spacer" }, { text: "Diagnosis", style: "heading" }, { text: `${primary.code} ${primary.title}`, style: "normal" });
    }
    return [...lines, ...footer()];
  }

  if (kind === "medicalLeave") {
    const ml = plan?.medicalLeave;
    if (!ml?.enabled) return null;
    const days = (() => {
      if (!ml.startDate || !ml.endDate) return null;
      const s = new Date(ml.startDate), e = new Date(ml.endDate);
      if (Number.isNaN(s.getTime()) || Number.isNaN(e.getTime())) return null;
      return Math.max(1, Math.round((e.getTime() - s.getTime()) / 86400000) + 1);
    })();
    return [
      ...header("Medical leave certificate", ctx),
      { text: ctx.medicalLeaveNumber ? `Certificate no. ${ctx.medicalLeaveNumber}` : "Medical leave certificate", style: "muted" },
      { style: "spacer" },
      { text: "Leave", style: "heading" },
      { text: `Type: ${ml.reason ?? "Medical leave"}`, style: "normal" },
      { text: `From: ${fmtDate(ml.startDate)}`, style: "normal" },
      { text: `To: ${fmtDate(ml.endDate)}`, style: "normal" },
      { text: `Duration: ${days ? `${days} day${days === 1 ? "" : "s"}` : "—"}`, style: "normal" },
      ...(primary ? [{ style: "spacer" as const }, { text: "Diagnosis", style: "heading" as const }, { text: `${primary.code} ${primary.title}`, style: "normal" as const }] : []),
      { style: "spacer" },
      { text: "Note", style: "heading" },
      { text: plan?.summary?.instructions?.trim() || "Rest at home; fit to return at the end of the leave unless reviewed.", style: "normal" },
      ...footer(),
    ];
  }

  if (kind === "summary") {
    const lines: PdfLine[] = [...header("Consultation summary", ctx)];
    if (primary) lines.push({ text: "Diagnosis", style: "heading" }, { text: `${primary.code} ${primary.title}`, style: "normal" }, { style: "spacer" });
    lines.push({ text: "Summary", style: "heading" }, { text: plan?.summary?.text?.trim() || "Not written", style: "normal" }, { style: "spacer" });
    lines.push({ text: "Instructions", style: "heading" }, { text: plan?.summary?.instructions?.trim() || "Not written", style: "normal" });
    if (plan?.followUp?.enabled) {
      lines.push({ style: "spacer" }, { text: "Follow-up", style: "heading" },
        { text: `${plan.followUp.mode ?? "Video check-in"}${plan.followUp.inDays ? ` · in ${plan.followUp.inDays} days` : ""}${plan.followUp.date ? ` · ${fmtDate(plan.followUp.date)}` : ""}`, style: "normal" });
    }
    return [...lines, ...footer()];
  }

  // receipt — always available (from the booking fee)
  return [
    ...header("Receipt", ctx),
    { text: "Payment", style: "heading" },
    { text: `Consultation: ${ctx.mode === "audio" ? "Audio" : "Video"} consultation with ${ctx.doctorName}`, style: "normal" },
    { text: `Amount: ${ctx.feeLabel ?? "—"}`, style: "normal" },
    { text: `Reference: ${ctx.reference}`, style: "normal" },
    { text: `Date: ${fmtDateTime(ctx.issuedAt)}`, style: "normal" },
    ...footer(),
  ];
}

const FILENAME: Record<DocKind, string> = {
  prescription: "prescription",
  medicalLeave: "medical-leave",
  summary: "consultation-summary",
  receipt: "receipt",
};

export function viewDoc(kind: DocKind, ctx: DocsContext): void {
  const lines = buildDocLines(kind, ctx);
  if (!lines) return;
  viewPdf(buildPdf(lines));
}

export function downloadDoc(kind: DocKind, ctx: DocsContext): void {
  const lines = buildDocLines(kind, ctx);
  if (!lines) return;
  downloadPdf(buildPdf(lines), `${FILENAME[kind]}-${ctx.reference}`);
}

export function downloadAll(ctx: DocsContext): void {
  (["prescription", "medicalLeave", "summary", "receipt"] as DocKind[]).forEach((k, i) => {
    const lines = buildDocLines(k, ctx);
    if (lines) window.setTimeout(() => downloadPdf(buildPdf(lines), `${FILENAME[k]}-${ctx.reference}`), i * 250);
  });
}
